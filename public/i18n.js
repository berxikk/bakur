/**
 * Universal key lookup across both app & community dictionaries
 */
export function getTranslation(key, currentLang) {
  const l = currentLang || (typeof localStorage !== 'undefined' ? localStorage.getItem('amed_lang') : 'tr') || 'tr';
  return (
    I18N[l]?.[key] ??
    CI18N[l]?.[key] ??
    I18N.tr?.[key] ??
    CI18N.tr?.[key] ??
    key
  );
}

/**
 * Automatically scans and translates every element in the DOM
 */
export function translateDocument(targetLang) {
  const l = targetLang || (typeof localStorage !== 'undefined' ? localStorage.getItem('amed_lang') : 'tr') || 'tr';
  document.documentElement.lang = l;

  // 1. Text elements: data-i18n and data-ci18n
  document.querySelectorAll('[data-i18n], [data-ci18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n') || el.getAttribute('data-ci18n');
    const val = getTranslation(key, l);
    if (typeof val === 'string') el.textContent = val;
  });

  // 2. Placeholders: data-i18n-ph, data-ci18n-ph
  document.querySelectorAll('[data-i18n-ph], [data-ci18n-ph]').forEach((el) => {
    const key = el.getAttribute('data-i18n-ph') || el.getAttribute('data-ci18n-ph');
    const val = getTranslation(key, l);
    if (typeof val === 'string') el.placeholder = val;
  });

  // 3. Titles and aria-labels: data-i18n-title, data-ci18n-title
  document.querySelectorAll('[data-i18n-title], [data-ci18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title') || el.getAttribute('data-ci18n-title');
    const val = getTranslation(key, l);
    if (typeof val === 'string') {
      el.title = val;
      el.setAttribute('aria-label', val);
    }
  });
}

// Global browser scope registration
if (typeof window !== 'undefined') {
  window.I18N = I18N;
  window.CI18N = CI18N;
  window.getTranslation = getTranslation;
  window.translateDocument = translateDocument;
}

export default { I18N, CI18N, getTranslation, translateDocument };
